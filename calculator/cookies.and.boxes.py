def print_pack_report(starting_value):
    # 1. Объявляем цикл, который перебирает числа от starting_value до 1 включительно.
    # range(старт, стоп, шаг). Стоп (1) не включается, поэтому ставим 0.
    # Шаг -1 означает движение в обратном порядке (убывание).
    for number in range(starting_value, 0, -1):

        # 2. Проверяем условия делимости.
        # Оператор % (остаток от деления) возвращает 0, если число делится без остатка.

        # Сначала проверяем самое строгое условие: делится И на 3, И на 5.
        if number % 3 == 0 and number % 5 == 0:
            print(f'{number} - расфасуем по 3 или по 5')

        # Если первое условие не прошло, проверяем, делится ли только на 3.
        # Нам не нужно писать "and number % 5 != 0", так как если бы оно делилось на 5,
        # мы бы уже попали в первый блок if.
        elif number % 3 == 0:
            print(f'{number} - расфасуем по 3')

        # Аналогично, проверяем делимость только на 5.
        elif number % 5 == 0:
            print(f'{number} - расфасуем по 5')

        # Если ни одно из условий выше не выполнилось, значит число не делится ни на 3, ни на 5.
        else:
            print(f'{number} - не заказываем!')


# Пример вызова функции (можно поменять число на любое другое)
print_pack_report(31)
